export const answerValueSchema = z.union([z.string().max(TEXT_ANSWER_MAX), z.boolean()]);
export type Answers = Record<string, string | boolean>;

export const registrationInputSchema = z.object({
  name: personNameSchema,
  email: emailSchema,
  locale: localeSchema,
  answers: z.record(fieldKeySchema, answerValueSchema).default({}),
});
export type RegistrationInput = z.infer<typeof registrationInputSchema>;

export type AnswerIssue = { key: string; problem: "required" | "invalid" | "unknown" };

/** Validates answers against the event's field definitions and returns the normalized answers. */
export function validateAnswers(
  fields: readonly RegistrationField[],
  answers: Record<string, unknown>,
): { ok: true; answers: Answers } | { ok: false; issues: AnswerIssue[] } {
  const issues: AnswerIssue[] = [];
  const out: Answers = {};
  const known = new Set(fields.map((f) => f.key));
  for (const key of Object.keys(answers)) {
    if (!known.has(key)) issues.push({ key, problem: "unknown" });
  }
  for (const field of fields) {
    const value = answers[field.key];
    if (field.type === "checkbox") {
      if (value !== undefined && typeof value !== "boolean")
        issues.push({ key: field.key, problem: "invalid" });
      else if (field.required && value !== true)
        issues.push({ key: field.key, problem: "required" });
      else out[field.key] = value === true;
      continue;
    }
    const text = typeof value === "string" ? value.trim() : value;
    if (text === undefined || text === "") {
      if (field.required) issues.push({ key: field.key, problem: "required" });
      continue;
    }
    if (typeof text !== "string" || text.length > TEXT_ANSWER_MAX) {
      issues.push({ key: field.key, problem: "invalid" });
    } else if (field.type === "select" && !field.options.includes(text)) {
      issues.push({ key: field.key, problem: "invalid" });
    } else {
      out[field.key] = text;
    }
  }
  return issues.length > 0 ? { ok: false, issues } : { ok: true, answers: out };
}

export const attendeeStatuses = ["active", "cancelled"] as const;
export const attendeeSources = ["open_registration", "import", "manual"] as const;
export const ticketStatuses = ["active", "superseded", "revoked"] as const;
export type TicketStatus = (typeof ticketStatuses)[number];

export const attendeeSchema = z.object({
  id: z.uuid(),
  name: z.string(),
  email: z.string(),
  status: z.enum(attendeeStatuses),
  source: z.enum(attendeeSources),
  answers: z.record(z.string(), answerValueSchema),
  ticketStatus: z.enum(ticketStatuses).nullable(),
  createdAt: instantSchema,
});
export type Attendee = z.infer<typeof attendeeSchema>;

/** What the attendee sees on their "my ticket" page. */
export const ticketViewSchema = z.object({
  attendee: z.object({ name: z.string(), status: z.enum(attendeeStatuses) }),
  event: publicEventSchema.pick({
    slug: true,
    name: true,
    startsAt: true,
    endsAt: true,
    timezone: true,
    venueName: true,
    venueAddress: true,
    organizerName: true,
  }),
  ticket: z.object({
    status: z.enum(ticketStatuses),
    /** Present only while the ticket is valid. */
    qrToken: z.string().nullable(),
  }),
});
export type TicketView = z.infer<typeof ticketViewSchema>;

export const registrationResultSchema = z.object({ status: z.literal("registered") });
