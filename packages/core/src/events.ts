import { z } from "zod";
import { emailSchema, personNameSchema } from "./auth.ts";
import { localeSchema } from "./locale.ts";
import { isValidTimeZone } from "./timezone.ts";

export const EVENT_NAME_MAX = 120;
export const EVENT_DESCRIPTION_MAX = 5_000;
export const MAX_REGISTRATION_FIELDS = 10;
export const MAX_SELECT_OPTIONS = 20;
export const TEXT_ANSWER_MAX = 500;

export const eventStatuses = ["draft", "published", "closed"] as const;
export type EventStatus = (typeof eventStatuses)[number];
export const registrationModes = ["open", "closed"] as const;
export type RegistrationMode = (typeof registrationModes)[number];

export const timeZoneSchema = z
  .string()
  .min(1)
  .max(64)
  .refine(isValidTimeZone, { message: "Unknown time zone" });

const instantSchema = z.iso.datetime({ offset: true });

/** Field keys are generated by the client (`f1`, `f2`, ...) and stay stable across edits. */
const fieldKeySchema = z.string().regex(/^[a-z][a-z0-9_]{0,31}$/);
const fieldLabelSchema = z.string().trim().min(1).max(100);

export const registrationFieldSchema = z.discriminatedUnion("type", [
  z.object({
    type: z.literal("text"),
    key: fieldKeySchema,
    label: fieldLabelSchema,
    required: z.boolean(),
  }),
  z.object({
    type: z.literal("select"),
    key: fieldKeySchema,
    label: fieldLabelSchema,
    required: z.boolean(),
    options: z.array(z.string().trim().min(1).max(100)).min(1).max(MAX_SELECT_OPTIONS),
  }),
  z.object({
    type: z.literal("checkbox"),
    key: fieldKeySchema,
    label: fieldLabelSchema,
    required: z.boolean(),
  }),
]);
export type RegistrationField = z.infer<typeof registrationFieldSchema>;

export const registrationFieldsSchema = z
  .array(registrationFieldSchema)
  .max(MAX_REGISTRATION_FIELDS)
  .refine((fields) => new Set(fields.map((f) => f.key)).size === fields.length, {
    message: "Field keys must be unique",
  });

const eventFields = {
  name: z.string().trim().min(1).max(EVENT_NAME_MAX),
  description: z.string().trim().max(EVENT_DESCRIPTION_MAX).nullable(),
  startsAt: instantSchema,
  endsAt: instantSchema.nullable(),
  timezone: timeZoneSchema,
  venueName: z.string().trim().min(1).max(200),
  venueAddress: z.string().trim().max(500).nullable(),
  capacity: z.number().int().min(1).max(100_000).nullable(),
  registrationMode: z.enum(registrationModes),
  registrationDeadline: instantSchema.nullable(),
  registrationFields: registrationFieldsSchema,
};

export interface DateIssue {
  path: ["endsAt"] | ["registrationDeadline"];
  message: string;
}

/** Cross-field date rules, shared by create (schema) and update (merged event in the API). */
export function eventDateIssues(event: {
  startsAt: string;
  endsAt: string | null;
  registrationDeadline: string | null;
}): DateIssue[] {
  const issues: DateIssue[] = [];
  if (event.endsAt && Date.parse(event.endsAt) <= Date.parse(event.startsAt)) {
    issues.push({ path: ["endsAt"], message: "endsAt must be after startsAt" });
  }
  const end = event.endsAt ?? event.startsAt;
  if (event.registrationDeadline && Date.parse(event.registrationDeadline) > Date.parse(end)) {
    issues.push({
      path: ["registrationDeadline"],
      message: "registrationDeadline must not be after the event ends",
    });
  }
  return issues;
}

export const eventInputSchema = z.object(eventFields).superRefine((event, ctx) => {
  for (const issue of eventDateIssues(event)) ctx.addIssue({ code: "custom", ...issue });
});
export type EventInput = z.infer<typeof eventInputSchema>;

/** PATCH body: any subset of fields. Cross-field rules are re-checked on the merged event. */
export const eventUpdateSchema = z.object(eventFields).partial();
export type EventUpdate = z.infer<typeof eventUpdateSchema>;

export const eventSchema = z.object({
  id: z.uuid(),
  organizationId: z.uuid(),
  slug: z.string(),
  ...eventFields,
  status: z.enum(eventStatuses),
  registeredCount: z.number().int(),
  createdAt: instantSchema,
  updatedAt: instantSchema,
});
export type Event = z.infer<typeof eventSchema>;

